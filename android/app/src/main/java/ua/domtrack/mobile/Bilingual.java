    static String city(String s) {
        String n = Model.normalized(s);
        return ALIASES.getOrDefault(n, n);
    }

    static String text(String s) {
        String n = Model.normalized(s)
            .replace('’', '\'')
            .replace('ʼ', '\'')
            .replaceAll("[^\\p{L}\\p{N}'-]+", " ");
        ArrayList<String> out = new ArrayList<>();
        for (String word : n.split(" +"))
            if (!word.isBlank()) out.add(ALIASES.getOrDefault(word, word));
        return String.join(" ", out);
    }

    static boolean contains(String haystack, String query) {
        Set<String> words = new HashSet<>(Arrays.asList(text(haystack).split(" +")));
        for (String q : text(query).split(" +"))
            if (!q.isBlank() && !words.contains(q)) return false;
        return true;
    }
